def add_run(paragraph, text, bold=False, size=11, color=None):
    run = paragraph.add_run(text)
    run.bold = bold
    run.font.name = "Microsoft YaHei"
    run.font.size = Pt(size)
    if color:
        run.font.color.rgb = RGBColor(*color)
    return run


def main():
    OUT.parent.mkdir(parents=True, exist_ok=True)
    doc = Document()
    section = doc.sections[0]
    section.top_margin = Pt(54)
    section.bottom_margin = Pt(54)
    section.left_margin = Pt(54)
    section.right_margin = Pt(54)

    styles = doc.styles
    styles["Normal"].font.name = "Microsoft YaHei"
    styles["Normal"].font.size = Pt(11)
    styles["Title"].font.name = "Microsoft YaHei"
    styles["Heading 1"].font.name = "Microsoft YaHei"
    styles["Heading 2"].font.name = "Microsoft YaHei"

    title = doc.add_paragraph()
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    add_run(title, "牧云智舍路演演讲稿（逐页版）", bold=True, size=20, color=(0, 96, 64))

    subtitle = doc.add_paragraph()
    subtitle.alignment = WD_ALIGN_PARAGRAPH.CENTER
    add_run(subtitle, "根据《终稿.pptx》与《牧云智舍-商业计划书.docx》整理", size=10, color=(90, 90, 90))

    note = doc.add_paragraph()
    add_run(note, "使用建议：", bold=True, size=11)
    add_run(note, "每页先按“页面作用”把握讲述目的，再用“建议讲稿”进行口头表达；正式路演时可根据限时压缩细节。", size=11)

    for idx, (heading, purpose, script) in enumerate(slides, start=1):
        p = doc.add_paragraph()
        p.style = doc.styles["Heading 1"]
        add_run(p, f"第 {idx} 页：{heading}", bold=True, size=15, color=(0, 96, 64))

        purpose_p = doc.add_paragraph()
        add_run(purpose_p, "页面作用：", bold=True, size=11, color=(42, 117, 83))
        add_run(purpose_p, purpose, size=11)

        script_p = doc.add_paragraph()
        add_run(script_p, "建议讲稿：", bold=True, size=11, color=(42, 117, 83))

        body = doc.add_paragraph()
        body.paragraph_format.line_spacing = 1.25
        body.paragraph_format.space_after = Pt(8)
        add_run(body, script, size=11)

    doc.save(OUT)
    print(str(OUT))


