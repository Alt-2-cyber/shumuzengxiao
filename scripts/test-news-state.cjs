const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const Module = require('node:module');
const ts = require('../wx/node_modules/typescript');
const filename = path.resolve(__dirname, '../wx/miniprogram/utils/news-state.ts');
const compiled = ts.transpileModule(fs.readFileSync(filename, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } });
const stateModule = new Module(filename);
stateModule._compile(compiled.outputText, filename);
const {emptyNewsState,applyNewsFeed,markNewsRead,markAllNewsRead,toggleNewsFavorite,unreadNewsCount,articleDate}=stateModule.exports;
function article(id,kind='news',category='health') { return {id,kind,category,title:id,summary:'',content:'',sourceName:'test',sourceUrl:'https://www.nahs.org.cn/',publishedAt:'2026-09-28T16:00:00Z',collectedAt:'2026-10-22T00:00:00Z'}; }
const feed={articles:[article('a'),article('b','news','market'),article('tip','knowledge')],sources:[],dailyDate:'2026-10-22',dailyKnowledgeId:'tip',refreshing:false,generatedAt:'2026-10-22T00:00:00Z'};
let state=applyNewsFeed(emptyNewsState(),feed,'2026-10-22T01:00:00Z');
assert.equal(state.messages.length,3);
assert.equal(applyNewsFeed(state,feed,'2026-10-22T02:00:00Z').messages.length,3,'same-day refresh must not duplicate messages');
state=markNewsRead(state,'a');assert.equal(state.messages.find(item=>item.articleId==='a').read,true);
assert.equal(unreadNewsCount(markAllNewsRead(state)),0);
state=toggleNewsFavorite(state,feed.articles[0]);
state=applyNewsFeed(state,{...feed,articles:feed.articles.slice(1)},'2026-10-22T03:00:00Z');
assert.equal(state.favorites[0].id,'a','favorites outside the current feed must remain readable');
assert.equal(toggleNewsFavorite(state,feed.articles[0]).favorites.length,0);
let disabled=emptyNewsState();disabled.preferences.newsEnabled=false;disabled.preferences.dailyKnowledge=false;
disabled=applyNewsFeed(disabled,feed,'2026-10-22T01:00:00Z');assert.equal(disabled.messages.length,0);
disabled.preferences.newsEnabled=true;
assert.equal(applyNewsFeed(disabled,feed,'2026-10-22T02:00:00Z').messages.length,0,'reenabling must not replay historical news');
disabled.preferences.categories=['health'];
const fresh=applyNewsFeed(disabled,{...feed,articles:[article('fresh'),article('market','news','market'),...feed.articles]},'2026-10-22T03:00:00Z');
assert.deepEqual(fresh.messages.map(item=>item.articleId),['fresh']);
assert.equal(applyNewsFeed(state,{...feed,dailyDate:'2026-10-23'},'2026-10-23T00:00:00Z').messages.filter(item=>item.id.startsWith('tip:')).length,2);
assert.equal(articleDate(feed.articles[0]),'2026-09-29','publisher dates must use Asia/Shanghai');
console.log('News state checks passed: daily deduplication, subscriptions, unread, favorites and publisher dates.');
