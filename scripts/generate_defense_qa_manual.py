def set_run(run, bold=False, size=11, color=None):
    run.bold = bold
    run.font.name = "Microsoft YaHei"
    run.font.size = Pt(size)
    if color:
        run.font.color.rgb = RGBColor(*color)


def paragraph(doc, text="", bold=False, size=11, color=None, style=None):
    p = doc.add_paragraph()
    if style:
        p.style = style
    run = p.add_run(text)
    set_run(run, bold=bold, size=size, color=color)
    return p


def labeled_paragraph(doc, label, text):
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(4)
    r1 = p.add_run(label)
    set_run(r1, bold=True, size=10.5, color=(42, 117, 83))
    r2 = p.add_run(text)
    set_run(r2, size=10.5)
    return p


