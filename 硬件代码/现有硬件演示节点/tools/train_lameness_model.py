def fail(message: str) -> None:
    raise SystemExit(message)


def numeric(value: Any) -> float:
    if not isinstance(value, (int, float)) or not math.isfinite(float(value)):
        raise ValueError("non-finite numeric reading")
    return float(value)


def magnitude(reading: dict[str, Any], gyro: bool = False) -> float:
    axes = ("gx", "gy", "gz") if gyro else ("ax", "ay", "az")
    return math.sqrt(sum(numeric(reading[axis]) ** 2 for axis in axes))


def stats(values: list[float]) -> tuple[float, float, float, float]:
    array = np.asarray(values, dtype=np.float64)
    deltas = np.abs(np.diff(array))
    return (
        float(array.mean()),
        float(array.std(ddof=0)),
        float(deltas.mean()) if deltas.size else 0.0,
        float(deltas.std(ddof=0)) if deltas.size else 0.0,
    )


def load_rows(path: Path) -> list[dict[str, Any]]:
    if not path.is_file():
        fail(f"raw IMU file not found: {path}")
    rows: list[dict[str, Any]] = []
    for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), start=1):
        if not line.strip():
            continue
        try:
            row = json.loads(line)
            if row.get("type") != "motion_capture_sample":
                continue
            for position in POSITIONS:
                if not isinstance(row.get(position), dict):
                    raise ValueError(f"missing {position}")
            rows.append(row)
        except (json.JSONDecodeError, ValueError, KeyError) as exc:
            fail(f"invalid raw IMU row at {path}:{number}: {exc}")
    if not rows:
        fail(f"raw IMU file has no motion_capture_sample rows: {path}")
    return rows


def resolve_path(reference: str, data_root: Path) -> Path:
    value = Path(reference)
    return value if value.is_absolute() else data_root / value


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as source:
        for block in iter(lambda: source.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def required_text(record: dict[str, Any], field: str) -> str:
    value = str(record.get(field) or "").strip()
    if not value:
        fail(f"record {record.get('recordingId')} has no {field}")
    return value


def fetch_json(url: str, api_key: str, timeout_seconds: int) -> dict[str, Any]:
    request = urllib.request.Request(
        url,
        headers={"Authorization": f"Bearer {api_key}", "Accept": "application/json"},
    )
    try:
        with urllib.request.urlopen(request, timeout=timeout_seconds) as response:
            payload = json.loads(response.read().decode("utf-8"))
    except urllib.error.HTTPError as error:
        body = error.read().decode("utf-8", "replace")
        fail(f"motion-capture lineage API returned HTTP {error.code}: {body}")
    except urllib.error.URLError as error:
        fail(f"cannot reach motion-capture lineage API: {error}")
    if not isinstance(payload, dict):
        fail("motion-capture lineage API returned a non-object response")
    return payload


def verify_release_lineage(
        args: argparse.Namespace,
        records: list[dict[str, Any]],
        data_root: Path,
) -> dict[str, Any]:
    """Recheck every release sample against the protected IMU archive.

    The CSV-derived manifest is useful for reproducibility, but it is not the
    authority for capture identity or raw-data integrity. Every row must still
    match the current accepted platform archive at the time of training.
    """
    if not args.clinical_api or not args.clinical_api_key:
        fail("--release requires --clinical-api and --clinical-api-key for motion-capture lineage recheck")
    if args.lineage_timeout_seconds < 1 or args.lineage_timeout_seconds > 120:
        fail("lineage timeout must be between 1 and 120 seconds")

    base_url = args.clinical_api.rstrip("/")
    checked: list[dict[str, Any]] = []
    seen_sessions: set[str] = set()
    seen_recordings: set[str] = set()
    for record in records:
        recording_id = required_text(record, "recordingId")
        if recording_id in seen_recordings:
            fail(f"release manifest reuses recordingId {recording_id}")
        seen_recordings.add(recording_id)
        session_id = required_text(record, "recordingSessionId")
        if session_id in seen_sessions:
            fail(f"release manifest reuses recordingSessionId {session_id}")
        seen_sessions.add(session_id)
        animal_id = required_text(record, "animalId")
        video_reference = required_text(record, "videoReference")
        for field in (
                "gaitReviewer", "hoofExaminer", "veterinarian", "hoofFinding",
                "clinicalEvidenceReference", "verifiedAt"):
            required_text(record, field)
        if not bool(record.get("clinicalVerified")) or not bool(record.get("allowForDiseaseLabels")):
            fail(f"record {recording_id} is not clinically eligible for disease labels")
        try:
            score = int(record["lamenessScore"])
        except (KeyError, TypeError, ValueError) as error:
            fail(f"record {recording_id} has an invalid lamenessScore: {error}")
        if score < 0 or score > 3:
            fail(f"record {recording_id} lamenessScore must be 0..3")
        target_label = "lameness_suspect" if score >= 2 else "normal_gait"
        if str(record.get("targetLabel") or "") != target_label:
            fail(f"record {recording_id} targetLabel does not match lamenessScore")

        quality = record.get("imuQuality")
        if not isinstance(quality, dict):
            fail(f"record {recording_id} has no verified IMU quality block")
        local_hash = str(quality.get("sha256") or "").lower()
        if len(local_hash) != 64 or any(character not in "0123456789abcdef" for character in local_hash):
            fail(f"record {recording_id} has an invalid IMU SHA-256")
        raw_path = resolve_path(required_text(record, "imuReference"), data_root)
        if not raw_path.is_file() or sha256_file(raw_path) != local_hash:
            fail(f"local IMU archive changed before platform recheck for {recording_id}")

        endpoint = urllib.parse.urljoin(
            base_url + "/", f"api/motion-captures/{urllib.parse.quote(session_id, safe='')}/training-lineage")
        remote = fetch_json(endpoint, args.clinical_api_key, args.lineage_timeout_seconds)
        comparisons = {
            "sessionId": (str(remote.get("sessionId") or ""), session_id),
            "cattleId": (str(remote.get("cattleId") or ""), animal_id),
            "rawDataSha256": (str(remote.get("rawDataSha256") or "").lower(), local_hash),
            "videoReference": (str(remote.get("videoReference") or ""), video_reference),
        }
        mismatched = [field for field, (actual, expected) in comparisons.items() if actual != expected]
        if remote.get("status") != "completed":
            mismatched.append("status")
        if remote.get("qualityStatus") != "accepted":
            mismatched.append("qualityStatus")
        if remote.get("archiveIntegrityVerified") is not True:
            mismatched.append("archiveIntegrityVerified")
        if remote.get("clinicalReviewStatus") != "verified":
            mismatched.append("clinicalReviewStatus")
        clinical_comparisons = {
            "lamenessScore": (remote.get("lamenessScore"), score),
            "gaitReviewer": (str(remote.get("gaitReviewer") or ""), required_text(record, "gaitReviewer")),
            "hoofExaminer": (str(remote.get("hoofExaminer") or ""), required_text(record, "hoofExaminer")),
            "veterinarian": (str(remote.get("veterinarian") or ""), required_text(record, "veterinarian")),
            "hoofFinding": (str(remote.get("hoofFinding") or ""), required_text(record, "hoofFinding")),
            "clinicalEvidenceReference": (
                str(remote.get("clinicalEvidenceReference") or ""),
                required_text(record, "clinicalEvidenceReference")),
            "clinicallyVerifiedAt": (str(remote.get("clinicallyVerifiedAt") or ""), required_text(record, "verifiedAt")),
        }
        mismatched.extend(
            field for field, (actual, expected_value) in clinical_comparisons.items() if actual != expected_value)
        if remote.get("sampleRateHz") != SAMPLE_RATE_HZ:
            mismatched.append("sampleRateHz")
        received = remote.get("receivedSamples")
        expected = remote.get("expectedSamples")
        attempted = remote.get("attemptedSamples")
        if not all(isinstance(value, int) for value in (received, expected, attempted)) \
                or expected <= 0 or received / expected < 0.95 or attempted != expected:
            mismatched.append("sampleCounts")
        if remote.get("droppedBackpressureSamples") not in (0, None) \
                or remote.get("droppedSensorSamples") not in (0, None):
            mismatched.append("droppedSamples")
        if mismatched:
            fail(f"platform lineage mismatch for recordingId {recording_id}: {', '.join(mismatched)}")
        checked.append({
            "recordingId": recording_id,
            "recordingSessionId": session_id,
            "animalId": animal_id,
            "rawDataSha256": local_hash,
            "videoReference": video_reference,
            "sampleRateHz": SAMPLE_RATE_HZ,
            "receivedSamples": received,
            "expectedSamples": expected,
            "attemptedSamples": attempted,
            "completenessRatio": remote.get("completenessRatio"),
            "gaitReviewer": required_text(record, "gaitReviewer"),
            "hoofExaminer": required_text(record, "hoofExaminer"),
            "veterinarian": required_text(record, "veterinarian"),
            "hoofFinding": required_text(record, "hoofFinding"),
            "clinicalEvidenceReference": required_text(record, "clinicalEvidenceReference"),
            "verifiedAt": required_text(record, "verifiedAt"),
            "lamenessScore": score,
        })

    if not checked:
        fail("--release needs at least one platform-archived IMU session")
    canonical = json.dumps(checked, sort_keys=True, separators=(",", ":"))
    return {
        "checked": len(checked),
        "recordingSessionIds": [record["recordingSessionId"] for record in checked],
        "records": checked,
        "fingerprint": hashlib.sha256(canonical.encode("utf-8")).hexdigest(),
        "api": base_url,
    }


def verify_record_lineage(record: dict[str, Any], data_root: Path, require_platform: bool) -> None:
    quality = record.get("imuQuality")
    if not isinstance(quality, dict):
        fail(f"record {record.get('recordingId')} has no verified IMU quality block")
    declared_hash = str(quality.get("sha256") or "").lower()
    if len(declared_hash) != 64:
        fail(f"record {record.get('recordingId')} has no IMU SHA-256")
    raw_path = resolve_path(str(record["imuReference"]), data_root)
    if not raw_path.is_file() or sha256_file(raw_path) != declared_hash:
        fail(f"raw IMU SHA-256 does not match verified manifest for {record.get('recordingId')}")
    if require_platform:
        platform = quality.get("platformSession")
        if not isinstance(platform, dict) or platform.get("status") != "completed" \
                or platform.get("qualityStatus") != "accepted" \
                or platform.get("clinicalReviewStatus") != "verified" \
                or str(platform.get("rawDataSha256") or "").lower() != declared_hash:
            fail(f"release requires an accepted platform session with matching hash for {record.get('recordingId')}")


def windows_for_record(record: dict[str, Any], data_root: Path, window_samples: int, hop_samples: int) -> list[Window]:
    raw_path = resolve_path(str(record["imuReference"]), data_root)
    rows = load_rows(raw_path)
    ordered = sorted(rows, key=lambda row: int(row.get("sampleIndex", 0)))
    label = 1 if int(record["lamenessScore"]) >= 2 else 0
    output: list[Window] = []
    for start in range(0, len(ordered) - window_samples + 1, hop_samples):
        segment = ordered[start:start + window_samples]
        try:
            neck_acc = [magnitude(row["neck"]) for row in segment]
            body_acc = [magnitude(row["body"]) for row in segment]
            leg_acc = [magnitude(row["leg"]) for row in segment]
        except (KeyError, ValueError) as exc:
            fail(f"invalid IMU axes in {raw_path}: {exc}")
        values = np.asarray(
            stats(neck_acc) + stats(body_acc) + stats(leg_acc),
            dtype=np.float64,
        )
        output.append(Window(values, label, str(record["animalId"]), str(record["recordingId"])))
    if not output:
        fail(f"record {record['recordingId']} has less than one {window_samples / SAMPLE_RATE_HZ:g}s window")
    return output


def grouped_partitions(windows: list[Window], seed: int) -> tuple[set[str], set[str], set[str]]:
    by_animal: dict[str, list[Window]] = defaultdict(list)
    for row in windows:
        by_animal[row.animal_id].append(row)
    animals = list(by_animal)
    if len(animals) < 9:
        fail("need at least 9 independent animals for train/validation/external-test release partitions")
    random.Random(seed).shuffle(animals)
    external_count = max(3, round(len(animals) * 0.20))
    validation_count = max(2, round(len(animals) * 0.20))
    external = set(animals[:external_count])
    validation = set(animals[external_count:external_count + validation_count])
    train = set(animals[external_count + validation_count:])
    if not train or not validation or not external:
        fail("animal-group split produced an empty partition")
    for name, groups in (("train", train), ("validation", validation), ("external", external)):
        labels = {row.label for animal in groups for row in by_animal[animal]}
        if labels != {0, 1}:
            fail(f"{name} animal partition does not contain both normal and lameness labels")
    return train, validation, external


def fit_logistic(x: np.ndarray, y: np.ndarray, epochs: int, learning_rate: float, l2: float) -> tuple[np.ndarray, float, np.ndarray, np.ndarray]:
    mean = x.mean(axis=0)
    scale = x.std(axis=0)
    scale[scale < 1e-6] = 1.0
    normalized = (x - mean) / scale
    weights = np.zeros(normalized.shape[1], dtype=np.float64)
    bias = 0.0
    for _ in range(epochs):
        logits = normalized @ weights + bias
        probabilities = 1.0 / (1.0 + np.exp(-np.clip(logits, -40, 40)))
        error = probabilities - y
        weights -= learning_rate * ((normalized.T @ error) / len(y) + l2 * weights)
        bias -= learning_rate * float(error.mean())
    return weights, bias, mean, scale


def probability(x: np.ndarray, weights: np.ndarray, bias: float, mean: np.ndarray, scale: np.ndarray) -> np.ndarray:
    logits = ((x - mean) / scale) @ weights + bias
    return 1.0 / (1.0 + np.exp(-np.clip(logits, -40, 40)))


def threshold_for_validation(y: np.ndarray, probabilities: np.ndarray) -> float:
    best = (float("-inf"), 0.5)
    for threshold in np.linspace(0.35, 0.90, num=56):
        predicted = (probabilities >= threshold).astype(np.int8)
        metric = metrics(y, predicted, np.zeros_like(y, dtype=bool))["balancedAccuracy"]
        candidate = (metric, float(threshold))
        if candidate > best:
            best = candidate
    return best[1]


def metrics(y: np.ndarray, prediction: np.ndarray, rejected: np.ndarray) -> dict[str, float | int]:
    accepted = ~rejected
    scored_y = y[accepted]
    scored_prediction = prediction[accepted]
    tp = int(np.sum((scored_y == 1) & (scored_prediction == 1)))
    tn = int(np.sum((scored_y == 0) & (scored_prediction == 0)))
    fp = int(np.sum((scored_y == 0) & (scored_prediction == 1)))
    fn = int(np.sum((scored_y == 1) & (scored_prediction == 0)))
    sensitivity = tp / (tp + fn) if tp + fn else 0.0
    specificity = tn / (tn + fp) if tn + fp else 0.0
    precision = tp / (tp + fp) if tp + fp else 0.0
    npv = tn / (tn + fn) if tn + fn else 0.0
    return {
        "tp": tp, "tn": tn, "fp": fp, "fn": fn,
        "sensitivity": sensitivity, "specificity": specificity,
        "ppv": precision, "npv": npv,
        "balancedAccuracy": (sensitivity + specificity) / 2,
        "rejectRate": float(rejected.mean()) if rejected.size else 1.0,
        "acceptedWindows": int(accepted.sum()),
    }


def rejection_limits(x_train: np.ndarray, y_train: np.ndarray, mean: np.ndarray, scale: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    normalized = (x_train - mean) / scale
    centroids = np.vstack([normalized[y_train == label].mean(axis=0) for label in (0, 1)])
    limits = np.empty(2, dtype=np.float64)
    for label in (0, 1):
        distances = np.sum(np.square(normalized[y_train == label] - centroids[label]), axis=1)
        limits[label] = float(np.quantile(distances, 0.98))
    return centroids, limits


def make_prediction(x: np.ndarray, weights: np.ndarray, bias: float, mean: np.ndarray, scale: np.ndarray,
                    threshold: float, centroids: np.ndarray, limits: np.ndarray) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    probabilities = probability(x, weights, bias, mean, scale)
    raw = (probabilities >= threshold).astype(np.int8)
    normalized = (x - mean) / scale
    distances = np.sum(np.square(normalized - centroids[raw]), axis=1)
    rejected = distances > limits[raw]
    return raw, rejected, probabilities


def false_positives_per_animal_day(windows: list[Window], prediction: np.ndarray, rejected: np.ndarray,
                                   window_seconds: float, hop_seconds: float) -> float:
    by_animal: dict[str, list[tuple[Window, int, bool]]] = defaultdict(list)
    for row, predicted, reject in zip(windows, prediction, rejected):
        by_animal[row.animal_id].append((row, int(predicted), bool(reject)))
    rates: list[float] = []
    observation_seconds = max(window_seconds, len(by_animal) and hop_seconds or window_seconds)
    for rows in by_animal.values():
        false_positive = sum(1 for row, predicted, reject in rows if row.label == 0 and predicted == 1 and not reject)
        hours = max(len(rows) * hop_seconds / 3600.0, observation_seconds / 3600.0)
        rates.append(false_positive / hours * 24.0)
    return float(np.mean(rates)) if rates else float("inf")


def cpp_float(value: float) -> str:
    text = f"{float(value):.8g}"
    if "e" not in text and "." not in text:
        text += ".0"
    return text + "f"


def export_header(output: Path, weights: np.ndarray, bias: float, mean: np.ndarray, scale: np.ndarray,
                  centroids: np.ndarray, limits: np.ndarray, threshold: float, version: str, enabled: bool) -> None:
    values = lambda array: ", ".join(cpp_float(item) for item in array.ravel())
    centroid_rows = ",\n    ".join("{" + values(row) + "}" for row in centroids)
    header = f'''#pragma once

#include <Arduino.h>
#include <math.h>

// Generated by tools/train_lameness_model.py. This is a lameness screening
// candidate, not a diagnosis of lameness cause, side, lesion, or disease.
namespace cattle_lameness_model {{

constexpr bool kEnabled = {str(enabled).lower()};
constexpr uint8_t kFeatureCount = {len(FEATURE_NAMES)};
constexpr const char *kVersion = "{version}";
constexpr float kProbabilityThreshold = {cpp_float(threshold)};
static const float kWeights[kFeatureCount] = {{{values(weights)}}};
constexpr float kBias = {cpp_float(bias)};
static const float kMean[kFeatureCount] = {{{values(mean)}}};
static const float kScale[kFeatureCount] = {{{values(scale)}}};
static const float kCentroids[2][kFeatureCount] = {{
    {centroid_rows}
}};
static const float kDistanceLimits[2] = {{{values(limits)}}};

struct Prediction {{ bool suspect; bool rejected; float score; }};

inline Prediction predict(const float *features) {{
  float logit = kBias;
  float normalized[kFeatureCount];
  for (uint8_t index = 0; index < kFeatureCount; index++) {{
    normalized[index] = (features[index] - kMean[index]) / kScale[index];
    logit += normalized[index] * kWeights[index];
  }}
  const float score = 1.0f / (1.0f + expf(-constrain(logit, -40.0f, 40.0f)));
  const uint8_t predicted = score >= kProbabilityThreshold ? 1 : 0;
  float distance = 0.0f;
  for (uint8_t index = 0; index < kFeatureCount; index++) {{
    const float delta = normalized[index] - kCentroids[predicted][index];
    distance += delta * delta;
  }}
  if (distance > kDistanceLimits[predicted]) {{
    return {{false, true, score}};
  }}
  return {{predicted == 1, false, score}};
}}

}}  // namespace cattle_lameness_model
'''
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(header, encoding="utf-8", newline="\n")


def write_model_card(path: Path, report: dict[str, Any]) -> None:
    ext = report["externalTest"]
    gate = report["releaseGate"]
    lines = [
        "# Three-position lameness screening model card", "",
        f"- Version: `{report['modelVersion']}`",
        f"- Deployment status: `{'approved' if gate['approved'] else 'disabled'}`",
        "- Input: 20 Hz neck/body/leg ADXL345 acceleration; 10 s windows / 5 s hop.",
        "- Output: `lameness_suspect` screening candidate or rejection, never disease diagnosis.",
        f"- External animals: {report['externalAnimals']}; external windows: {report['externalWindows']}",
        "",
        "## External test", "",
        f"- Sensitivity: {ext['sensitivity']:.3f}",
        f"- Specificity: {ext['specificity']:.3f}",
        f"- PPV: {ext['ppv']:.3f}",
        f"- NPV: {ext['npv']:.3f}",
        f"- Rejection rate: {ext['rejectRate']:.3f}",
        f"- False positives per animal-day: {report['falsePositivesPerAnimalDay']:.3f}",
        "", "## Release gate", "",
    ]
    lines.extend(f"- {reason}" for reason in gate["reasons"] or ["All release gates passed."])
    lines.extend(["", "## Limits", "", "A positive result is a request for gait scoring, hoof examination and veterinary review. It does not establish foot rot, sole ulcer, digital dermatitis, arthritis, trauma, foot-and-mouth disease, or any other disease.", ""])
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8", newline="\n")


def main() -> None:
    args = parse_args()
    if not args.manifest.is_file():
        fail(f"manifest not found: {args.manifest}")
    if args.window_seconds < 5 or args.hop_seconds <= 0 or args.hop_seconds > args.window_seconds:
        fail("window and hop seconds are invalid")
    manifest = json.loads(args.manifest.read_text(encoding="utf-8"))
    records = manifest.get("records")
    if not isinstance(records, list) or not records:
        fail("manifest does not contain records")
    root = args.data_root or args.manifest.parent
    platform_lineage: dict[str, Any] | None = None
    for record in records:
        if not isinstance(record, dict):
            fail("manifest contains a non-object record")
        verify_record_lineage(record, root, args.release)
    if args.release:
        platform_lineage = verify_release_lineage(args, records, root)
    window_samples = round(args.window_seconds * SAMPLE_RATE_HZ)
    hop_samples = round(args.hop_seconds * SAMPLE_RATE_HZ)
    all_windows = [window for record in records for window in windows_for_record(record, root, window_samples, hop_samples)]
    train_animals, validation_animals, external_animals = grouped_partitions(all_windows, args.seed)
    select = lambda animals: [row for row in all_windows if row.animal_id in animals]
    train_rows, validation_rows, external_rows = select(train_animals), select(validation_animals), select(external_animals)
    x_train, y_train = np.vstack([row.features for row in train_rows]), np.asarray([row.label for row in train_rows])
    x_validation, y_validation = np.vstack([row.features for row in validation_rows]), np.asarray([row.label for row in validation_rows])
    x_external, y_external = np.vstack([row.features for row in external_rows]), np.asarray([row.label for row in external_rows])
    weights, bias, mean, scale = fit_logistic(x_train, y_train, args.epochs, args.learning_rate, args.l2)
    threshold = threshold_for_validation(y_validation, probability(x_validation, weights, bias, mean, scale))
    centroids, limits = rejection_limits(x_train, y_train, mean, scale)
    predicted, rejected, probabilities = make_prediction(x_external, weights, bias, mean, scale, threshold, centroids, limits)
    external = metrics(y_external, predicted, rejected)
    false_positive_rate = false_positives_per_animal_day(external_rows, predicted, rejected, args.window_seconds, args.hop_seconds)
    positive_animals = {row.animal_id for row in external_rows if row.label == 1}
    reasons: list[str] = []
    if not args.release:
        reasons.append("release was not requested; header remains disabled")
    if args.release and (platform_lineage is None
                         or int(platform_lineage.get("checked", 0)) != len(records)):
        reasons.append("motion-capture platform lineage was not rechecked for every training record")
    if len(external_animals) < args.minimum_external_animals:
        reasons.append(f"external test has {len(external_animals)} animals; requires {args.minimum_external_animals}")
    if len(positive_animals) < args.minimum_positive_animals:
        reasons.append(f"external test has {len(positive_animals)} positive animals; requires {args.minimum_positive_animals}")
    for key, actual, required in (
        ("sensitivity", external["sensitivity"], args.minimum_sensitivity),
        ("specificity", external["specificity"], args.minimum_specificity),
        ("ppv", external["ppv"], args.minimum_ppv),
    ):
        if float(actual) < required:
            reasons.append(f"external {key} {float(actual):.3f} is below {required:.3f}")
    if float(external["rejectRate"]) > args.maximum_reject_rate:
        reasons.append(f"external rejection rate {float(external['rejectRate']):.3f} exceeds {args.maximum_reject_rate:.3f}")
    if false_positive_rate > args.maximum_false_positives_per_animal_day:
        reasons.append(f"false positives per animal-day {false_positive_rate:.3f} exceeds {args.maximum_false_positives_per_animal_day:.3f}")
    approved = args.release and not reasons
    fingerprint = hashlib.sha256(args.manifest.read_bytes()).hexdigest()
    version = f"three-position-lameness-{fingerprint[:12]}"
    export_header(args.output, weights, bias, mean, scale, centroids, limits, threshold, version, approved)
    report: dict[str, Any] = {
        "modelVersion": version, "generatedAt": datetime.now(UTC).isoformat(),
        "manifest": str(args.manifest.resolve()), "manifestFingerprint": fingerprint,
        "featureNames": FEATURE_NAMES, "windowSeconds": args.window_seconds, "hopSeconds": args.hop_seconds,
        "trainAnimals": len(train_animals), "validationAnimals": len(validation_animals), "externalAnimals": len(external_animals),
        "trainWindows": len(train_rows), "validationWindows": len(validation_rows), "externalWindows": len(external_rows),
        "externalTest": external, "falsePositivesPerAnimalDay": false_positive_rate,
        "motionPlatformLineage": platform_lineage,
        "releaseGate": {"requested": args.release, "approved": approved, "reasons": reasons},
        "scope": "Screening only; veterinary gait scoring and hoof examination remain required.",
    }
    args.metadata.parent.mkdir(parents=True, exist_ok=True)
    args.metadata.write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    write_model_card(args.model_card, report)
    print(json.dumps(report, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
