#!/usr/bin/env python3
"""Train a gated three-position accelerometer lameness *screening* model for ESP32.

The input manifest must be produced by verify_lameness_manifest.py and point
to raw 20 Hz NDJSON capture files generated by the firmware. The trainer uses
animal-grouped partitions, retains an external test group, and refuses to
enable the firmware header unless all clinical and operating gates pass.
"""

