import numpy as np


FEATURE_NAMES = (
    "neck_acc_mean", "neck_acc_std", "neck_acc_delta_mean", "neck_acc_delta_std",
    "body_acc_mean", "body_acc_std", "body_acc_delta_mean", "body_acc_delta_std",
    "leg_acc_mean", "leg_acc_std", "leg_acc_delta_mean", "leg_acc_delta_std",
)
POSITIONS = ("neck", "body", "leg")
SAMPLE_RATE_HZ = 20


@dataclass(frozen=True)
class Window:
    features: np.ndarray
    label: int
    animal_id: str
    recording_id: str


